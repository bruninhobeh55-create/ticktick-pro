function buildRecentLogs(daysChecked: number[], targetValue: number) {
  const logs: Habit['logs'] = {};
  daysChecked.forEach((offset) => {
    const key = format(subDays(today, offset), 'yyyy-MM-dd');
    logs[key] = {
      value: targetValue,
      completed: true,
      mood: offset % 2 === 0 ? 'great' : 'good',
      note: offset === 0 ? 'Felt super energized!' : undefined,
      timestamp: `${key}T08:30:00.000Z`,
    };
  });
  return logs;
}

